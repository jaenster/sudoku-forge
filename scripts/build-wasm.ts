// Compile the Zig core to WebAssembly and embed it as a TypeScript module, so
// the web build is a single self-contained page with no separate .wasm fetch.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

mkdirSync("build", { recursive: true });
mkdirSync("web/src/generated", { recursive: true });

execFileSync(
  process.env.ZIG ?? "zig",
  ["build-exe", "core/solver.zig", "-target", "wasm32-freestanding", "-O", "ReleaseFast", "-fno-entry", "-rdynamic", "-femit-bin=build/solver.wasm"],
  { stdio: "inherit" },
);

const wasm = readFileSync("build/solver.wasm");
writeFileSync(
  "web/src/generated/solver-wasm.ts",
  `// Generated by scripts/build-wasm.ts. Do not edit.\nexport const SOLVER_WASM_BASE64 =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`solver.wasm ${(wasm.length / 1024).toFixed(0)} KB`);

// The designer itself: the same app the native builds use, with the solver
// linked in, behind a canvas backend (native/web.zig).
const zig = process.env.ZIG ?? "zig";
execFileSync(zig, ["build-obj", "core/solver.zig", "-target", "wasm32-freestanding", "-O", "ReleaseFast", "-femit-bin=build/solver-wasm.o"], { stdio: "inherit" });
execFileSync(
  zig,
  ["build-exe", "native/web.zig", "build/solver-wasm.o", "-target", "wasm32-freestanding", "-O", "ReleaseSmall", "-fno-entry", "-rdynamic", "-femit-bin=build/app.wasm"],
  { stdio: "inherit" },
);
const appWasm = readFileSync("build/app.wasm");
writeFileSync(
  "web/src/generated/app-wasm.ts",
  `// Generated by scripts/build-wasm.ts. Do not edit.\nexport const APP_WASM_BASE64 =\n  "${appWasm.toString("base64")}";\n`,
);
console.log(`app.wasm ${(appWasm.length / 1024).toFixed(0)} KB`);
