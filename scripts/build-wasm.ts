// Compile the Zig core to WebAssembly and embed it as a TypeScript module, so
// the web build is a single self-contained page with no separate .wasm fetch.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

mkdirSync("build", { recursive: true });
mkdirSync("web/src/generated", { recursive: true });

execFileSync(
  process.env.ZIG ?? "zig",
  ["build-exe", "core/solver.zig", "-target", "wasm32-freestanding", "-O", "ReleaseFast", "-fno-entry", "-rdynamic", "-femit-bin=build/solver.wasm"],
  { stdio: "inherit" },
);

const wasm = readFileSync("build/solver.wasm");
writeFileSync(
  "web/src/generated/solver-wasm.ts",
  `// Generated by scripts/build-wasm.ts. Do not edit.\nexport const SOLVER_WASM_BASE64 =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`solver.wasm ${(wasm.length / 1024).toFixed(0)} KB`);
